#!/usr/bin/env bun
import path from "node:path"
import { renderBunfig } from "../src/lint/bun"
import { formatOptions, type LintRule, lintRules } from "../src/lint/configs/bun.default"

const ROOT = path.resolve(import.meta.dir, "..")
const OUT = "bunfig.toml"
const HEADER = "# Generated by scripts/gen-bunfig.ts. Do not edit: run `bun run gen-bunfig`.\n\n"

/** Rules the aid repository adds on top of the bundled defaults. */
export const repoRules: Record<string, LintRule> = {
  "import/no-default-export": "error",
  "import/no-namespace": "error",
  curly: ["error", "all"],
  "@typescript-eslint/consistent-type-definitions": ["error", "type"],
  "prefer-arrow-callback": "error",
  "promise/prefer-await-to-then": "error",
}

/** The repository's `bunfig.toml`. */
export const repoBunfig = (): string =>
  HEADER +
  renderBunfig({
    lint: { rules: { ...lintRules, ...repoRules } },
    fmt: { ...formatOptions, sortTailwindcss: true },
  })

if (import.meta.main) {
  const content = repoBunfig()
  const target = Bun.file(path.join(ROOT, OUT))
  if (process.argv.includes("--check")) {
    if (!(await target.exists()) || (await target.text()) !== content) {
      console.error(`[gen-bunfig] ${OUT} is out of date. Run 'bun run gen-bunfig' and commit it.`)
      process.exit(1)
    }
    console.log(`[gen-bunfig] ${OUT} is in sync.`)
  } else {
    await Bun.write(target, content)
    console.log(`[gen-bunfig] wrote ${OUT}.`)
  }
}
