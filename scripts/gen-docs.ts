const MARKER = "<!-- Generated by scripts/gen-docs.ts. Do not edit: run `bun run gen-docs`. -->"

/** JSON Schema node, as far as the reference pages read it. */
export type SchemaNode = {
  type?: string
  description?: string
  default?: unknown
  enum?: unknown[]
  const?: unknown
  minimum?: number
  maximum?: number
  minLength?: number
  format?: string
  items?: SchemaNode
  properties?: Record<string, SchemaNode>
  required?: string[]
}

/** One documented key: its dotted path and the schema node behind it. */
export type SchemaRow = { key: string; node: SchemaNode; required: boolean }

/** One generated file, relative to the repo root. */
export type GeneratedFile = { path: string; content: string }

/** Input-mode JSON Schema, so defaulted keys read as optional, as they are at runtime. */
export function inputSchema(schema: z.ZodType): SchemaNode {
  const { $schema: _, ...rest } = z.toJSONSchema(schema, { io: "input" }) as SchemaNode & {
    $schema?: string
  }
  return rest
}

/** Every leaf key under `node`, depth first, with object keys joined by dots. */
export function schemaRows(node: SchemaNode, prefix = ""): SchemaRow[] {
  return Object.entries(node.properties ?? {}).flatMap(([name, child]) => {
    const key = prefix === "" ? name : `${prefix}.${name}`
    if (child.type === "object" && child.properties) {
      return schemaRows(child, key)
    }
    return [{ key, node: child, required: node.required?.includes(name) ?? false }]
  })
}

/** Escape text for a markdown table cell or paragraph: no raw HTML, no stray pipes. */
export function escapeMd(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("|", "\\|")
    .replace(/https?:\/\/[^\s)]+/g, (url) => `\`${url}\``)
}

function code(value: string): string {
  return `\`${value.replaceAll("|", "\\|")}\``
}

function typeLabel(node: SchemaNode): string {
  if (node.enum) {
    return `one of ${node.enum.map((v) => code(String(v))).join(", ")}`
  }
  if (node.const !== undefined) {
    return code(String(node.const))
  }
  if (node.type === "array" && node.items) {
    return `list of ${typeLabel(node.items)}`
  }
  const bounds = [
    node.minimum !== undefined ? `min ${node.minimum}` : null,
    node.maximum !== undefined ? `max ${node.maximum}` : null,
    node.minLength !== undefined ? "non-empty" : null,
    node.format === "uri" ? "URL" : null,
  ].filter((b) => b !== null)
  const base = node.type ?? "any"
  return bounds.length > 0 ? `${base} (${bounds.join(", ")})` : base
}

function defaultLabel(row: SchemaRow): string {
  if (row.required) {
    return "required"
  }
  return row.node.default === undefined ? "none" : code(JSON.stringify(row.node.default))
}

function fence(lang: string, body: string): string {
  return `\`\`\`${lang}\n${body}\n\`\`\``
}

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n")
}

function keyTable(rows: SchemaRow[]): string {
  return table(
    ["Key", "Type", "Default", "Description"],
    rows.map((r) => [
      code(r.key),
      typeLabel(r.node),
      defaultLabel(r),
      escapeMd(r.node.description ?? ""),
    ]),
  )
}

function page(front: { title: string; description: string; order: number }, body: string): string {
  return [
    "---",
    `title: ${front.title}`,
    `description: ${front.description}`,
    "sidebar:",
    `  order: ${front.order}`,
    "---",
    "",
    MARKER,
    "",
    body.trim(),
    "",
  ].join("\n")
}

async function resolve<T>(value: Resolvable<T>): Promise<T> {
  return typeof value === "function" ? await (value as () => T | Promise<T>)() : await value
}

function argName(name: string, def: ArgDef): string {
  if (def.type === "positional") {
    return code(name.toUpperCase())
  }
  const aliases = ["alias" in def ? (def.alias ?? []) : []].flat().map((a) => code(`-${a}`))
  return [code(`--${name}`), ...aliases].join(", ")
}

function argType(def: ArgDef): string {
  if (def.type === "enum" && "options" in def && def.options) {
    return `one of ${def.options.map((o) => code(String(o))).join(", ")}`
  }
  return def.type ?? "string"
}

/** CLI reference page, built from the citty definitions the binary itself runs. */
export async function cliReference(root: CommandDef = main): Promise<string> {
  const rootMeta = await resolve(root.meta ?? {})
  const subCommands = (await resolve(root.subCommands ?? {})) as Record<
    string,
    Resolvable<CommandDef>
  >
  const sections: string[] = []
  for (const [name, load] of Object.entries(subCommands)) {
    const cmd = await resolve(load)
    const meta = await resolve(cmd.meta ?? {})
    const args = Object.entries((await resolve(cmd.args ?? {})) as Record<string, ArgDef>)
    const positionals = args
      .filter(([, def]) => def.type === "positional")
      .map(([n, def]) => (def.required ? n.toUpperCase() : `[${n.toUpperCase()}]`))
    const hasOptions = args.some(([, def]) => def.type !== "positional")
    const usage = ["aid", name, ...(hasOptions ? ["[OPTIONS]"] : []), ...positionals].join(" ")
    const rows = args.map(([n, def]) => [
      argName(n, def),
      argType(def),
      def.default === undefined ? "none" : code(String(def.default)),
      escapeMd(def.description ?? ""),
    ])
    sections.push(
      [
        `## \`aid ${name}\``,
        escapeMd(meta.description ?? ""),
        fence("sh", usage),
        rows.length > 0 ? table(["Argument", "Type", "Default", "Description"], rows) : "",
      ]
        .filter((s) => s !== "")
        .join("\n\n"),
    )
  }
  return page(
    {
      title: "CLI reference",
      description: "Every aid command, argument, and flag, generated from the CLI definitions.",
      order: 1,
    },
    [
      escapeMd(rootMeta.description ?? ""),
      "Running `aid` with no command prints help. Every command accepts `--help` (`-h`). `aid --version` prints the version.",
      ...sections,
    ].join("\n\n"),
  )
}

/** Configuration reference page for `aid.yaml`, built from the Zod schema. */
export function configReference(): string {
  const schema = inputSchema(AidConfigSchema)
  const props = schema.properties ?? {}
  const scalars: SchemaRow[] = []
  const groups: string[] = []
  for (const [name, node] of Object.entries(props)) {
    if (node.type === "object" && node.properties) {
      groups.push(
        [`## \`${name}\``, escapeMd(node.description ?? ""), keyTable(schemaRows(node, name))].join(
          "\n\n",
        ),
      )
    } else {
      scalars.push({ key: name, node, required: schema.required?.includes(name) ?? false })
    }
  }
  const defaults = Bun.YAML.stringify(AidConfigSchema.parse({ name: "My Docs" }), null, 2)
  return page(
    {
      title: "Configuration reference",
      description: "Every aid.yaml key with its type, default, and meaning.",
      order: 2,
    },
    [
      "aid reads `aid.yaml` from the project directory (`--file` picks another name). Only `name` is required. An unknown key is an error.",
      "## Top-level keys",
      keyTable(scalars),
      ...groups,
      "## Full default config",
      "This is the config aid builds with when `aid.yaml` holds only `name: My Docs`.",
      fence("yaml", stripTrailingSpaces(defaults).trim()),
    ].join("\n\n"),
  )
}

/** Frontmatter and `_meta.yaml` reference page, built from their Zod schemas. */
export function frontmatterReference(): string {
  const entry = inputSchema(NavMetaSchema)
  const entryNode = (entry as { additionalProperties?: SchemaNode }).additionalProperties ?? {}
  return page(
    {
      title: "Frontmatter reference",
      description: "Markdown frontmatter keys and the _meta.yaml sidebar file.",
      order: 3,
    },
    [
      "## Markdown frontmatter",
      "A markdown page may start with a YAML block between `---` lines. Other keys are allowed and ignored. Malformed YAML or a wrong type fails the build.",
      keyTable(schemaRows(inputSchema(FrontmatterSchema))),
      "## `_meta.yaml`",
      "Any content folder may hold a `_meta.yaml` that maps a child name (a page file name without its extension, or a subfolder name) to sidebar overrides. In the content root, the key `index` addresses the home page. An entry here wins over the page's own `sidebar` frontmatter. A key that matches nothing is a `nav/unknown-entry` problem, which fails the build unless `on_broken_links` is `warn`.",
      keyTable(schemaRows(entryNode)),
      "```yaml\ngetting-started: { order: 1 }\napi: { label: HTTP API, order: 2 }\n```",
    ].join("\n\n"),
  )
}

/** Lint and fmt defaults page: what each wrapped tool scans and which config it uses. */
export function lintDefaultsReference(): string {
  const rows = KNOWN_TOOLS.map((tool) => [
    code(tool),
    PATTERNS[tool].map(code).join(", "),
    USER_CONFIGS[tool].length === 0 ? "None" : USER_CONFIGS[tool].map(code).join(", "),
  ])
  return page(
    {
      title: "Lint and format defaults",
      description:
        "Files each aid lint and aid fmt tool scans, the config files it looks for, and its bundled defaults.",
      order: 4,
    },
    [
      "`aid lint` dispatches to five tools and `aid fmt` to four: `css` only lints. Each tool except `css` looks for its own config file, starting in the target directory and walking up until it reaches a directory that holds `.git`. Without one, the bundled default below applies. `aid lint` leaves CSS files to `css`, so `bun` only formats them.",
      table(["Tool", "Files", "Config files"], rows),
      `Discovery never walks into these directories: ${[...DEFAULT_IGNORES].map(code).join(", ")}.`,
      "## markdownlint default (`md`)",
      fence("json", JSON.stringify(markdownlintDefault, null, 2)),
      "## Spectral default (`openapi`)",
      "The bundled ruleset is `spectral:oas`.",
      "## bun default (`bun`)",
      "Without a lint config, `aid lint` turns off every `bun lint` rule category and runs only these rules. Without a formatter config, `aid fmt` passes these `bun fmt` options:",
      fence(
        "toml",
        Object.entries(formatOptions)
          .map(([k, v]) => `${k} = ${JSON.stringify(v)}`)
          .join("\n"),
      ),
      table(
        ["Rule", "Severity", "Options"],
        Object.entries(lintRules).map(([name, rule]) => {
          const [severity, ...options] = Array.isArray(rule) ? rule : [rule]
          return [
            code(name),
            String(severity),
            options.length === 0 ? "None" : code(JSON.stringify(options)),
          ]
        }),
      ),
      "## CSS checks (`css`)",
      "The `css` tool has no config file and always runs these checks. Codes match the Stylelint rule with the same intent.",
      table(
        ["Code", "Severity", "Reports"],
        Object.entries(CSS_RULES).map(([name, rule]) => [
          code(name),
          rule.severity,
          rule.description,
        ]),
      ),
      "## buf default (`proto`)",
      fence("yaml", bufDefault.trim()),
    ].join("\n\n"),
  )
}

/** OpenAPI 3.1 wrapper around the config and frontmatter schemas, so Scalar renders them as models. */
export function configSchemaOpenApi(): string {
  const doc = {
    openapi: "3.1.0",
    info: {
      title: "Configuration schema",
      version,
      description:
        "The aid.yaml, frontmatter, and _meta.yaml schemas, shown as OpenAPI models. Generated from the same Zod schemas that validate them at build time.",
    },
    paths: {},
    components: {
      schemas: {
        AidConfig: inputSchema(AidConfigSchema),
        Frontmatter: inputSchema(FrontmatterSchema),
        SidebarMeta: inputSchema(NavMetaSchema),
      },
    },
  }
  return `# Generated by scripts/gen-docs.ts. Do not edit: run \`bun run gen-docs\`.\n${stripTrailingSpaces(Bun.YAML.stringify(doc, null, 2)).trimEnd()}\n`
}

function referenceIndex(): string {
  return page(
    {
      title: "Reference",
      description:
        "Generated reference pages for the CLI, configuration, frontmatter, and lint defaults.",
      order: 0,
    },
    [
      "These pages come from the source code and are regenerated by `bun run gen-docs`. `bun run check` fails when they drift.",
      "- [CLI reference](./cli.md)",
      "- [Configuration reference](./configuration.md)",
      "- [Frontmatter reference](./frontmatter.md)",
      "- [Lint and format defaults](./lint-defaults.md)",
      "- [Configuration schema](./config-schema.yaml), the same schemas as interactive OpenAPI models",
      "- [aid.yaml JSON Schema](./aid-schema.json), the published editor schema rendered as field docs",
    ].join("\n\n"),
  )
}

function stripTrailingSpaces(text: string): string {
  return text.replace(/[ \t]+$/gm, "")
}

/** Every file this script owns, with its expected content. */
export async function generateAll(): Promise<GeneratedFile[]> {
  const publishedSchema = await Bun.file(path.join(ROOT, "schemas/aid.schema.json")).text()
  return [
    { path: `${REFERENCE_DIR}/index.md`, content: referenceIndex() },
    { path: `${REFERENCE_DIR}/cli.md`, content: await cliReference() },
    { path: `${REFERENCE_DIR}/configuration.md`, content: configReference() },
    { path: `${REFERENCE_DIR}/frontmatter.md`, content: frontmatterReference() },
    { path: `${REFERENCE_DIR}/lint-defaults.md`, content: lintDefaultsReference() },
    { path: `${REFERENCE_DIR}/config-schema.yaml`, content: configSchemaOpenApi() },
    { path: `${REFERENCE_DIR}/aid-schema.json`, content: publishedSchema },
    { path: "site/static/schemas/aid.schema.json", content: publishedSchema },
  ]
}

if (import.meta.main) {
  const files = await generateAll()
  if (process.argv.includes("--check")) {
    const drifted: string[] = []
    for (const file of files) {
      const existing = Bun.file(path.join(ROOT, file.path))
      if (!(await existing.exists()) || (await existing.text()) !== file.content) {
        drifted.push(file.path)
      }
    }
    if (drifted.length > 0) {
      console.error(
        `[gen-docs] out of date:\n${drifted.map((p) => `  ${p}`).join("\n")}\nRun 'bun run gen-docs' and commit the result.`,
      )
      process.exit(1)
    }
    console.log("[gen-docs] reference pages are in sync.")
  } else {
    await Promise.all(files.map((f) => Bun.write(path.join(ROOT, f.path), f.content)))
    console.log(`[gen-docs] wrote ${files.length} files.`)
  }
}
