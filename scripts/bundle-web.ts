#!/usr/bin/env bun
/**
 * Bundle the browser-side glue. Three entrypoints get bundled:
 *
 *   - `src/web/index.ts`         → `dist/web/aid-web.js`     (`aidWebJs`)
 *   - `src/web/mermaid-entry.ts` → `dist/web/aid-mermaid.js` (`aidMermaidJs`)
 *   - `src/web/openapi-entry.ts` → `dist/web/aid-openapi.js` (`aidOpenapiJs`)
 *
 * The minified ESM for each entry is written to **two** places:
 *
 *   1. `dist/web/<name>.js` — visible inspection artefact. Build pipelines or
 *      humans peeking at `dist/` can see the produced bytes.
 *   2. `src/web/_bundled.ts` — exported as a string so `src/core/web-bundle.ts`
 *      can embed it via a static import. Inside a `bun build --compile` binary
 *      this is the only path that works: there is no source tree to feed back
 *      into `Bun.build` at runtime, and `with { type: "text" }` requires a
 *      static path. `scripts/compile.ts` runs this script right before
 *      cross-compiling so the binary ships with the bundles embedded.
 */

import { resolve } from "node:path"

const ROOT = resolve(import.meta.dir, "..")
const DIST_WEB = resolve(ROOT, "dist", "web")
const BUNDLED_TS = resolve(ROOT, "src", "web", "_bundled.ts")

type Entry = {
  /** Identifier used for the `aid…Js` export name and the dist filename. */
  name: "aid-web" | "aid-mermaid" | "aid-openapi"
  /** TS source path bundle, relative to project root. */
  source: string
  /** Property name on `src/web/_bundled.ts`. */
  exportName: string
}

const ENTRIES: readonly Entry[] = [
  { name: "aid-web", source: "src/web/index.ts", exportName: "aidWebJs" },
  { name: "aid-mermaid", source: "src/web/mermaid-entry.ts", exportName: "aidMermaidJs" },
  { name: "aid-openapi", source: "src/web/openapi-entry.ts", exportName: "aidOpenapiJs" },
]

const fmtBytes = (n: number): string => {
  const units = ["B", "KB", "MB", "GB"]
  let i = 0
  let v = n
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024
    i++
  }
  return `${v.toFixed(v < 10 && i > 0 ? 2 : v < 100 && i > 0 ? 1 : 0)} ${units[i]}`
}

const bundleEntry = async (entry: Entry): Promise<string> => {
  const result = await Bun.build({
    entrypoints: [resolve(ROOT, entry.source)],
    target: "browser",
    format: "esm",
    minify: true,
  })
  if (!result.success) {
    for (const log of result.logs) console.error(log)
    throw new Error(`[bundle-web] failed to bundle ${entry.source}`)
  }
  const entryOutput = result.outputs.find((o) => o.kind === "entry-point")
  if (!entryOutput) throw new Error(`[bundle-web] no entry-point output for ${entry.source}`)
  return await entryOutput.text()
}

// Bun.write auto-creates the parent directories; no explicit mkdir needed.

const bundles: { entry: Entry; js: string }[] = []
for (const entry of ENTRIES) {
  const js = await bundleEntry(entry)
  const filename = `${entry.name}.js`
  const outPath = resolve(DIST_WEB, filename)
  await Bun.write(outPath, js)
  console.log(`[bundle-web] wrote dist/web/${filename} (${fmtBytes(js.length)})`)
  bundles.push({ entry, js })
}

const header = `/**
 * Generated by \`scripts/bundle-web.ts\`. Do NOT edit by hand.
 *
 * Each export holds the minified ESM string for one browser entrypoint.
 * Checked-in values are empty placeholders — in dev / \`bun test\` the runtime
 * (\`src/core/web-bundle.ts\`) detects the source tree on disk and compiles
 * each entry via \`Bun.build\`, ignoring these strings entirely.
 * \`scripts/compile.ts\` regenerates this file with real bytes right before
 * \`bun build --compile\` so the produced binary ships with the bundles
 * embedded as text and never needs \`Bun.build\` at runtime.
 *
 * After running \`bun scripts/bundle-web.ts\` manually, run
 * \`git checkout src/web/_bundled.ts\` to discard the generated diff before
 * committing.
 */\n\n`

const body = bundles
  .map(({ entry, js }) => `export const ${entry.exportName} = ${JSON.stringify(js)}\n`)
  .join("")

await Bun.write(BUNDLED_TS, header + body)
console.log(`[bundle-web] wrote src/web/_bundled.ts (${fmtBytes((header + body).length)})`)
