#!/usr/bin/env bun
import { resolve } from "node:path"
import { bundleWebEntry, AID_ROOT as ROOT, WEB_CSS, WEB_JS } from "../src/core/web-entries"

const DIST_WEB = resolve(ROOT, "dist", "web")
const outAt = process.argv.indexOf("--out")
const BUNDLED_TS =
  outAt === -1 ? resolve(ROOT, "src", "web", "_bundled.ts") : resolve(process.argv[outAt + 1] ?? "")

const fmtBytes = (n: number): string => {
  const units = ["B", "KB", "MB", "GB"]
  let i = 0
  let v = n
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024
    i++
  }
  return `${v.toFixed(v < 10 && i > 0 ? 2 : v < 100 && i > 0 ? 1 : 0)} ${units[i]}`
}

const buildProtoUi = () => Bun.$`bun run scripts/build.ts`.cwd(resolve(ROOT, "packages/proto-ui"))

const lines: string[] = []
const emit = async (filename: string, exportName: string, origin: string, body: string) => {
  await Bun.write(resolve(DIST_WEB, filename), body)
  console.log(`[bundle-web] wrote dist/web/${filename} (${fmtBytes(body.length)})`)
  lines.push(`/** ${origin}, embedded in the compiled binary. */\n`)
  lines.push(`export const ${exportName} = ${JSON.stringify(body)}\n`)
}

for (const entry of Object.values(WEB_JS)) {
  const js = await (await bundleWebEntry(entry)).text()
  await emit(`${entry.name}.js`, entry.exportName, `Minified ESM of \`${entry.source}\``, js)
}

await buildProtoUi()
for (const css of Object.values(WEB_CSS)) {
  const body = await Bun.file(Bun.resolveSync(css.specifier, ROOT)).text()
  await emit(`${css.name}.css`, css.exportName, `Stylesheet \`${css.specifier}\``, body)
}

const themeFiles = await Array.fromAsync(
  new Bun.Glob("src/theme/**/*.{tsx,ts}").scan({ cwd: ROOT }),
)
const themeSources = (
  await Promise.all(themeFiles.sort().map((file) => Bun.file(resolve(ROOT, file)).text()))
).join("\n")
lines.push(
  "/** Theme component sources, embedded so Tailwind finds their classes in the compiled binary. */\n",
)
lines.push(`export const aidThemeSources = ${JSON.stringify(themeSources)}\n`)
console.log(
  `[bundle-web] embedded ${themeFiles.length} theme sources (${fmtBytes(themeSources.length)})`,
)

const header = `/**
 * Generated by \`scripts/bundle-web.ts\`. Do not edit by hand.
 * Commit only the empty-string placeholders. Dev and tests build from source instead.
 */\n\n`

const body = lines.join("")

await Bun.write(BUNDLED_TS, header + body)
console.log(`[bundle-web] wrote ${BUNDLED_TS} (${fmtBytes((header + body).length)})`)
